"""Assemble AGENTOS_2_BENCHMARKS.md from the generated fragments in docs/benchmarks/fragments/."""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRAGMENTS = sorted((ROOT / "docs" / "benchmarks" / "fragments").glob("*.md"))
HEADER = """# AgentOS 2.0: benchmarks

_Generated by `benchmarks/assemble_v2_report.py` from per-suite fragments; do not edit by hand. Raw CSVs are in
`benchmarks/results/`, charts in `docs/benchmarks/`._

**Offline only.** No paid model was called. Where a suite uses the deterministic mock or fixture provider, its
quality numbers describe scripted behavior, not the intelligence of any real model, and costs are simulated.
"""


def main() -> None:
    body = "\n\n".join(p.read_text().rstrip() for p in FRAGMENTS)
    (ROOT / "AGENTOS_2_BENCHMARKS.md").write_text(HEADER + "\n" + body + "\n")
    print("wrote AGENTOS_2_BENCHMARKS.md from", [p.name for p in FRAGMENTS])


if __name__ == "__main__":
    main()
